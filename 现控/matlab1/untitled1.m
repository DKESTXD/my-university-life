% 生成传递函数 G(s) = 1/[s(s+1)(s+2)] 的奈奎斯特图
% 步骤1：定义传递函数的分子和分母多项式系数
num = 10;                  % 分子多项式：1（常数项）
den = conv([1 0], conv([1 1], [1 2]));  % 分母多项式：s(s+1)(s+2) = s³+3s²+2s
% 分解说明：
% conv([1 0], [1 1]) 计算 s(s+1) = s²+s，结果为 [1 1 0]
% 再与 [1 2] 卷积，得到 s(s+1)(s+2) = s³+3s²+2s，系数为 [1 3 2 0]

% 步骤2：创建线性时不变（LTI）系统模型
G = tf(num, den);         % tf函数用于创建传递函数模型

% 步骤3：绘制奈奎斯特图
figure;                   % 创建新图形窗口
nyquist(G);               % 绘制奈奎斯特图

